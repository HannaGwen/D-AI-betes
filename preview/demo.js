// A plausible, clearly synthetic glucose curve (mmol/L) for a given minute of the day.
function curve(min, dayIdx) {
  const bump = (start, amp) => { const x = min - start - 15; return x <= 0 ? 0 : amp * (x / 60) * Math.exp(1 - x / 60); };
  let g = 6.3 + bump(8 * 60, 3.4) + bump(12 * 60 + 45, 2.8) + bump(18 * 60 + 30, 4.6);
  g -= 0.8 * Math.exp(-(((min - 240) / 90) ** 2));
  if (dayIdx === 0) g -= 2.0 * Math.exp(-(((min - 1050) / 60) ** 2));
  const n = Math.sin(min * 12.9898 + dayIdx * 78.233) * 43758.5453;
  g += (n - Math.floor(n) - 0.5) * 0.5;
  return Math.min(16, Math.max(3.2, g));
}

function demoCsv(nowMs, tz) {
  const HEADER = "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mg/dL,Scan Glucose mg/dL,Non-numeric Rapid-Acting Insulin,Rapid-Acting Insulin (units),Non-numeric Food,Carbohydrates (grams),Carbohydrates (servings),Non-numeric Long-Acting Insulin,Long-Acting Insulin (units),Notes,Strip Glucose mg/dL,Ketone mmol/L,Meal Insulin (units),Correction Insulin (units),User Change Insulin (units)";
  const today = localDateKey(nowMs, tz);
  const lines = [`Glucose Data,Generated on,${new Date(nowMs).toISOString().slice(0, 16).replace("T", " ")} UTC,Generated by,Demo`, HEADER];
  const row = (ts, type, hist = "", scan = "") => ["FreeStyle LibreLink", "DEMO-SENSOR-1", ts, type, hist, scan, "", "", "", "", "", "", "", "", "", "", "", "", ""].join(",");
  [-1, 0].forEach((off, idx) => {
    const key = addDays(today, off), start = dayStartUtc(key, tz);
    const dayIdx = idx === 0 ? 0 : 1;
    for (let min = 0, k = 0; min < 24 * 60; min += 15, k++) {
      const t = start + (min + (k % 3 === 0 ? 1 : 0)) * 60000;
      if (t > nowMs) break;
      if (off === -1 && min >= 13 * 60 + 30 && min < 14 * 60 + 30) continue;           // a deliberate gap
      const p = utcToLocalParts(t, tz);
      const ts = `${p.y}-${z2(p.mo)}-${z2(p.d)} ${z2(p.h)}:${z2(p.mi)}`;
      lines.push(row(ts, 0, String(Math.round(curve(min, dayIdx) * MMOL))));
      if (min === 8 * 60 + 60 || min === 12 * 60 + 105) lines.push(row(ts, 1, "", String(Math.round(curve(min, dayIdx) * MMOL))));
    }
  });
  return lines.join("\n") + "\n";
}

function deleteDb(name) {
  return new Promise((res) => { const r = indexedDB.deleteDatabase(name); r.onsuccess = r.onerror = r.onblocked = () => res(); });
}

export async function mountDemo(root, { now = () => Date.now(), tz = deviceTimeZone(), dbName = "t1dlog-demo", iterations = 1000 } = {}) {
  await deleteDb(dbName);
  const store = new Store(dbName);
  const app = await start({ root, store, iterations, now, hideInstallHint: true });
  await store.create(DEMO_PASSPHRASE, { glucoseUnit: "mmol/L", tz, rapidName: "Rapid-acting (demo)", longName: "Long-acting (demo)",
    increment: 0.5, targetLowMgdl: 70, targetHighMgdl: 180, lockMinutes: 60, flagUnlogged: false }, { iterations });
  const nowMs = now();
  await store.importBatch(parseLibreView(new TextEncoder().encode(demoCsv(nowMs, tz)), { tz }), { tz, fileName: "demo-libreview.csv" });

  const today = localDateKey(nowMs, tz);
  for (const off of [-1, 0]) {
    const start0 = dayStartUtc(addDays(today, off), tz);
    for (const m of MEALS) {
      const t = start0 + m.min * 60000;
      if (t > nowMs) continue;
      const totals = { carb: 0, protein: 0, fat: 0, fibre: 0, sugar: 0 };
      for (const it of m.items) for (const k of Object.keys(totals)) totals[k] += it[k] || 0;
      for (const k of Object.keys(totals)) totals[k] = Math.round(totals[k] * 10) / 10;
      const meal = await store.put({ kind: "meal", t, tzName: tz, title: m.title, items: m.items, totals, carbsUsedForDosing: m.used, confidence: "medium", source: "app", loggedAt: t });
      const dt = t - m.pre * 60000;
      await store.put({ kind: "dose", t: dt, tzName: tz, role: "rapid", units: m.units, purpose: "meal", mealId: meal.id, insulin: "Rapid-acting (demo)", source: "app", confidence: "high", loggedAt: dt });
    }
    const lt = start0 + 22 * 60 * 60000;
    if (lt <= nowMs) await store.put({ kind: "dose", t: lt, tzName: tz, role: "long", units: 14, purpose: "basal", insulin: "Long-acting (demo)", source: "app", confidence: "high", loggedAt: lt });
  }
  const ex = dayStartUtc(addDays(today, -1), tz) + 17 * 60 * 60000;
  await store.put({ kind: "tag", tag: "exercise", t: ex, tzName: tz, durationMin: 30, payload: { type: "aerobic", intensity: 3, fasted: false }, source: "app" });
  await store.put({ kind: "saved_meal", name: MEALS[0].title, items: MEALS[0].items.map((i) => ({ ...i })) });

  app.S.screen = "main"; app.S.tab = "timeline"; app.S.day = null; app.render();
  return { app, store };
}
