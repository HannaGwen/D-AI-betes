"""
Reference parser for LibreView (FreeStyle Libre) CSV exports.

Purpose: prove the import rules in the Phase 0a spec (section 5) in Python before
they are re-implemented in Swift. Standard library only. Not a medical device and
not for treatment decisions.

Design rules implemented (see spec 5.2):
  1. Header-driven: header row is found by scanning the first few lines; columns
     are matched by name, never by position.
  2. Metadata: 'Generated on' is read for date disambiguation. The account name
     ('Generated by') and any name/date-of-birth row are DISCARDED, never stored.
  3. Delimiter detection (comma / semicolon / tab).
  4. Units from the header (mg/dL vs mmol/L); canonical storage is mg/dL, with the
     original value and unit kept.
  5. Date/time parsing without silent guessing: if day/month is ambiguous, the
     format is chosen using the file's 'Generated on' time; otherwise the parser
     raises AmbiguousDateFormat so the caller (user) must decide.
  6. Timestamps are local device time with no zone: the caller supplies a zone;
     daylight-saving repeats and gaps are flagged.
  7. Idempotent import: each row has a content hash; duplicates are dropped and an
     optional SQLite store ignores rows it has already seen.
  8. Irregular sampling is expected: gaps are computed from real timestamps.
  9. Unknown columns/record types are reported, not fatal.
 10. Traceability: source row number and file hash are kept.
"""

from __future__ import annotations

import csv
import hashlib
import io
import json
import re
import sqlite3
import statistics
from collections import Counter
from dataclasses import dataclass, field, asdict
from datetime import datetime, timedelta, timezone
from typing import Optional
from zoneinfo import ZoneInfo

MMOL_TO_MGDL = 18.0182

# --------------------------------------------------------------------------
# Errors
# --------------------------------------------------------------------------


class ParseError(Exception):
    """The file cannot be interpreted (no header, no usable columns, ...)."""


class AmbiguousDateFormat(ParseError):
    """Day/month order cannot be determined safely; the caller must choose."""

    def __init__(self, candidates):
        self.candidates = candidates
        super().__init__(
            "Date format is ambiguous. Candidates: "
            + ", ".join(candidates)
            + ". Pass date_format=... explicitly."
        )


# --------------------------------------------------------------------------
# Column handling
# --------------------------------------------------------------------------

# Canonical key -> regex on the normalised header (lowercase, spaces collapsed).
_COLUMN_PATTERNS = [
    ("device", r"^device$"),
    ("serial", r"^serial number$"),
    ("timestamp", r"^device timestamp$"),
    ("record_type", r"^record type$"),
    ("hist_glucose", r"^historic glucose"),
    ("scan_glucose", r"^scan glucose"),
    ("rapid_marker", r"^non-numeric rapid-acting insulin$"),
    ("rapid_units", r"^rapid-acting insulin \(units\)$"),
    ("food_marker", r"^non-numeric food$"),
    ("carbs_g", r"^carbohydrates \(grams\)$"),
    ("carbs_servings", r"^carbohydrates \(servings\)$"),
    ("long_marker", r"^non-numeric long-acting insulin$"),
    ("long_units", r"^long-acting insulin( value)? \(units\)$"),
    ("notes", r"^notes$"),
    ("strip_glucose", r"^strip glucose"),
    ("ketone", r"^ketone"),
    ("meal_insulin", r"^meal insulin \(units\)$"),
    ("correction_insulin", r"^correction insulin \(units\)$"),
    ("user_change_insulin", r"^user change insulin \(units\)$"),
]

_GLUCOSE_KEYS = ("hist_glucose", "scan_glucose", "strip_glucose")


def _norm_header(h: str) -> str:
    return re.sub(r"\s+", " ", h.strip().lower())


def _unit_from_header(h: str) -> Optional[str]:
    hl = h.lower()
    if "mmol" in hl:
        return "mmol/L"
    if "mg/dl" in hl or "mg/dl" in hl.replace(" ", ""):
        return "mg/dL"
    return None


# --------------------------------------------------------------------------
# Timestamp formats
# --------------------------------------------------------------------------

# Order matters only for reporting; ambiguity is resolved explicitly.
_DATE_FORMATS = [
    # month-first
    "%m-%d-%Y %I:%M %p", "%m-%d-%Y %I:%M:%S %p", "%m-%d-%Y %H:%M", "%m-%d-%Y %H:%M:%S",
    "%m/%d/%Y %I:%M %p", "%m/%d/%Y %I:%M:%S %p", "%m/%d/%Y %H:%M", "%m/%d/%Y %H:%M:%S",
    # day-first
    "%d-%m-%Y %I:%M %p", "%d-%m-%Y %I:%M:%S %p", "%d-%m-%Y %H:%M", "%d-%m-%Y %H:%M:%S",
    "%d/%m/%Y %I:%M %p", "%d/%m/%Y %I:%M:%S %p", "%d/%m/%Y %H:%M", "%d/%m/%Y %H:%M:%S",
    "%d.%m.%Y %H:%M", "%d.%m.%Y %H:%M:%S",
    # ISO-like (unambiguous)
    "%Y-%m-%d %H:%M", "%Y-%m-%d %H:%M:%S", "%Y/%m/%d %H:%M", "%Y/%m/%d %H:%M:%S",
]


def _try(fmt: str, s: str) -> Optional[datetime]:
    try:
        return datetime.strptime(s, fmt)
    except ValueError:
        return None


# --------------------------------------------------------------------------
# Data classes
# --------------------------------------------------------------------------


@dataclass
class Event:
    kind: str                     # glucose_auto | glucose_scan | glucose_strip | insulin | food | note | ketone
    local_time: datetime          # naive, device-local
    utc_time: datetime            # timezone-aware UTC
    source_row: int               # 1-based line number in the file (traceability)
    row_hash: str                 # content hash of the source row
    device: str = ""
    serial: str = ""
    flags: list = field(default_factory=list)
    data: dict = field(default_factory=dict)


@dataclass
class ParseResult:
    events: list
    report: dict
    file_hash: str


# --------------------------------------------------------------------------
# Helpers
# --------------------------------------------------------------------------


def _decode(raw: bytes) -> str:
    if raw.startswith(b"\xff\xfe") or raw.startswith(b"\xfe\xff"):
        return raw.decode("utf-16")
    try:
        return raw.decode("utf-8-sig")
    except UnicodeDecodeError:
        return raw.decode("latin-1")


def _detect_delimiter(header_line: str) -> str:
    counts = {d: header_line.count(d) for d in (",", ";", "\t")}
    best = max(counts, key=counts.get)
    return best if counts[best] > 0 else ","


def _find_header(lines: list, max_scan: int = 8):
    """Return index of the header row, found by known column names."""
    for i, line in enumerate(lines[:max_scan]):
        low = line.lower()
        if "device timestamp" in low and "record type" in low:
            return i
    raise ParseError(
        "Could not find a header row containing 'Device Timestamp' and 'Record Type' "
        f"in the first {max_scan} lines."
    )


def _parse_number(raw: str, delimiter: str):
    """Return (float|None, non_numeric_text|None)."""
    s = raw.strip()
    if s == "":
        return None, None
    t = s
    if "," in t and "." not in t and delimiter != ",":
        t = t.replace(",", ".")      # decimal comma in semicolon/tab files
    try:
        return float(t), None
    except ValueError:
        return None, s               # e.g. 'HI' / 'LO' style text, kept verbatim


def _local_to_utc(naive: datetime, tz: ZoneInfo):
    """Convert naive local time to UTC and report daylight-saving problems."""
    flags = []
    a = naive.replace(tzinfo=tz, fold=0)
    b = naive.replace(tzinfo=tz, fold=1)
    rt = a.astimezone(timezone.utc).astimezone(tz).replace(tzinfo=None)
    if rt != naive:
        flags.append("dst_nonexistent")      # skipped hour (clocks go forward)
    elif a.utcoffset() != b.utcoffset():
        flags.append("dst_ambiguous")        # repeated hour (clocks go back)
    return a.astimezone(timezone.utc), flags


# --------------------------------------------------------------------------
# Metadata (names are discarded)
# --------------------------------------------------------------------------


def _read_metadata(lines: list, header_idx: int, delimiter: str) -> dict:
    meta = {"generated_on_raw": None, "provider_export": False,
            "account_name_discarded": False, "extra_rows_discarded": 0}
    for i in range(header_idx):
        cells = next(csv.reader([lines[i]], delimiter=delimiter))
        cells = [c.strip() for c in cells]
        if i == 0:
            if cells and cells[0].lower().startswith("patient report"):
                meta["provider_export"] = True
            for j, c in enumerate(cells):
                if c.lower() == "generated on" and j + 1 < len(cells):
                    meta["generated_on_raw"] = re.sub(r"\s*UTC\s*$", "", cells[j + 1]).strip()
                if c.lower() == "generated by":
                    meta["account_name_discarded"] = True   # value is NOT read or kept
        else:
            meta["extra_rows_discarded"] += 1               # e.g. name / date of birth row
    return meta


# --------------------------------------------------------------------------
# Date format resolution
# --------------------------------------------------------------------------


def _resolve_date_format(raw_ts: list, generated_on_raw: Optional[str],
                         forced: Optional[str], max_unparsed_fraction: float = 0.01):
    """Choose a strptime format. Returns (format, how_resolved)."""
    if not raw_ts:
        raise ParseError("No data rows found.")
    if forced:
        return forced, "user_supplied"

    sample = list(dict.fromkeys(raw_ts))  # unique, order kept
    scored = []
    for fmt in _DATE_FORMATS:
        parsed = [_try(fmt, s) for s in sample]
        ok = [p for p in parsed if p is not None]
        failures = len(sample) - len(ok)
        if ok and failures <= max_unparsed_fraction * len(sample):
            scored.append((failures, fmt, max(ok)))
    if not scored:
        raise ParseError("No known timestamp format matches this file.")
    best_failures = min(s[0] for s in scored)
    candidates = [(f, mx) for fl, f, mx in scored if fl == best_failures]

    if len(candidates) == 1:
        return candidates[0][0], "unambiguous"

    # Ambiguous: use the export time. The newest reading in a correct reading of
    # the file is normally within a couple of days before 'Generated on'.
    if generated_on_raw:
        gens = [g for g in (_try(f, generated_on_raw) for f in _DATE_FORMATS) if g]
        close = []
        for fmt, mx in candidates:
            for g in gens:
                delta = g - mx
                if timedelta(days=-1) <= delta <= timedelta(days=2):
                    close.append(fmt)
                    break
        close = list(dict.fromkeys(close))
        # Formats that differ only in separator/clock style but agree on day/month
        # order describe the same instants; treat them as one answer.
        if len(close) == 1:
            return close[0], "resolved_by_generated_on"
        if len(close) > 1 and _same_instants(close, sample):
            return close[0], "resolved_by_generated_on"
    raise AmbiguousDateFormat([c[0] for c in candidates])


def _same_instants(formats: list, sample: list) -> bool:
    first = [_try(formats[0], s) for s in sample]
    return all([_try(f, s) for s in sample] == first for f in formats[1:])


# --------------------------------------------------------------------------
# Main parse
# --------------------------------------------------------------------------


def parse_libreview(path_or_bytes, tz_name: str = "Europe/London",
                    date_format: Optional[str] = None) -> ParseResult:
    if isinstance(path_or_bytes, (bytes, bytearray)):
        raw = bytes(path_or_bytes)
    else:
        with open(path_or_bytes, "rb") as fh:
            raw = fh.read()
    if not raw.strip():
        raise ParseError("File is empty.")
    file_hash = hashlib.sha256(raw).hexdigest()
    text = _decode(bytes(raw))
    lines = [ln for ln in text.splitlines() if ln.strip() != ""]
    tz = ZoneInfo(tz_name)

    # Header + metadata
    first_guess_delim = _detect_delimiter(lines[0]) if lines else ","
    header_idx = _find_header(lines)
    delimiter = _detect_delimiter(lines[header_idx])
    meta = _read_metadata(lines, header_idx, delimiter if delimiter else first_guess_delim)
    header = next(csv.reader([lines[header_idx]], delimiter=delimiter))

    # Column map (by name)
    colmap, units, unknown_cols = {}, {}, []
    for idx, h in enumerate(header):
        nh = _norm_header(h)
        hit = None
        for key, pat in _COLUMN_PATTERNS:
            if re.search(pat, nh):
                hit = key
                break
        if hit and hit not in colmap:
            colmap[hit] = idx
            if hit in _GLUCOSE_KEYS:
                units[hit] = _unit_from_header(h) or "mg/dL"
        else:
            unknown_cols.append(h)
    if "timestamp" not in colmap or "record_type" not in colmap:
        raise ParseError("Required columns (Device Timestamp, Record Type) not found.")
    if not any(k in colmap for k in _GLUCOSE_KEYS):
        raise ParseError("No glucose column found.")

    # Data rows (keeping 1-based file line numbers)
    original = text.splitlines()
    rows = []
    reader = csv.reader(lines[header_idx + 1:], delimiter=delimiter)
    # map back to original line numbers for traceability
    nonblank_numbers = [i + 1 for i, ln in enumerate(original) if ln.strip() != ""]
    for k, cells in enumerate(reader):
        rows.append((nonblank_numbers[header_idx + 1 + k], cells))

    def cell(cells, key):
        i = colmap.get(key)
        return cells[i].strip() if i is not None and i < len(cells) else ""

    ts_raw_all = [cell(c, "timestamp") for _, c in rows if len(c) == len(header)]
    fmt, how = _resolve_date_format(ts_raw_all, meta["generated_on_raw"], date_format)

    events, counters = [], Counter()
    seen_hashes = set()
    devices, serials = Counter(), Counter()
    type_counts = Counter()
    unparsed = []

    for line_no, cells in rows:
        if len(cells) != len(header):
            counters["rows_wrong_length"] += 1
            unparsed.append((line_no, "wrong number of fields"))
            continue
        ts_raw = cell(cells, "timestamp")
        local = _try(fmt, ts_raw)
        if local is None:
            counters["rows_bad_timestamp"] += 1
            unparsed.append((line_no, "timestamp does not match chosen format"))
            continue
        rtype = cell(cells, "record_type")
        type_counts[rtype] += 1
        device, serial = cell(cells, "device"), cell(cells, "serial")
        devices[device] += 1
        serials[serial] += 1

        data_cells = {k: cell(cells, k) for k in colmap
                      if k not in ("device", "serial", "timestamp", "record_type")}
        populated = {k: v for k, v in data_cells.items() if v != ""}

        if not populated:
            counters["empty_rows_discarded"] += 1     # e.g. blank type-6 rows
            continue

        row_hash = hashlib.sha256(
            "\x1f".join([serial, ts_raw, rtype] + [f"{k}={populated[k]}" for k in sorted(populated)]).encode()
        ).hexdigest()
        if row_hash in seen_hashes:
            counters["duplicate_rows_dropped"] += 1
            continue
        seen_hashes.add(row_hash)

        utc, dst_flags = _local_to_utc(local, tz)
        if dst_flags:
            counters["dst_flagged_rows"] += 1

        def add(kind, data, extra_flags=()):
            events.append(Event(kind=kind, local_time=local, utc_time=utc, source_row=line_no,
                                row_hash=row_hash, device=device, serial=serial,
                                flags=list(dst_flags) + list(extra_flags), data=data))

        produced = False

        # Glucose columns
        for key, kind, expect_type in (("hist_glucose", "glucose_auto", "0"),
                                       ("scan_glucose", "glucose_scan", "1"),
                                       ("strip_glucose", "glucose_strip", None)):
            if populated.get(key):
                val, text_val = _parse_number(populated[key], delimiter)
                unit = units.get(key, "mg/dL")
                fl = []
                if expect_type and rtype != expect_type:
                    fl.append(f"type_mismatch_expected_{expect_type}")
                if val is None:
                    add(kind, {"value_mgdl": None, "orig_value": text_val, "orig_unit": unit}, fl + ["non_numeric_glucose"])
                else:
                    mgdl = val * MMOL_TO_MGDL if unit == "mmol/L" else val
                    add(kind, {"value_mgdl": round(mgdl, 2), "orig_value": val, "orig_unit": unit}, fl)
                produced = True

        # Insulin columns (type 4 layout is unverified; columns drive the mapping)
        insulin_cols = (("rapid_units", "rapid_marker", "rapid", "unspecified"),
                        ("long_units", "long_marker", "long", "unspecified"),
                        ("meal_insulin", None, "rapid", "meal"),
                        ("correction_insulin", None, "rapid", "correction"),
                        ("user_change_insulin", None, "rapid", "user_change"))
        for ukey, mkey, role, purpose in insulin_cols:
            if populated.get(ukey) or (mkey and populated.get(mkey)):
                units_val, _ = _parse_number(populated.get(ukey, ""), delimiter)
                add("insulin", {"role": role, "purpose": purpose, "units": units_val,
                                "marker_only": units_val is None,
                                "confidence": "low", "source": "libre_app"})
                produced = True

        # Food
        if populated.get("carbs_g") or populated.get("carbs_servings") or populated.get("food_marker"):
            carbs, _ = _parse_number(populated.get("carbs_g", ""), delimiter)
            serv, _ = _parse_number(populated.get("carbs_servings", ""), delimiter)
            add("food", {"carbs_g": carbs, "servings": serv,
                         "marker_only": carbs is None and serv is None,
                         "confidence": "low", "source": "libre_app"})
            produced = True

        # Notes
        if populated.get("notes"):
            add("note", {"text": populated["notes"]})
            produced = True

        # Ketone
        if populated.get("ketone"):
            kv, _ = _parse_number(populated["ketone"], delimiter)
            add("ketone", {"value_mmol_l": kv})
            produced = True

        if not produced:
            counters["rows_with_unmapped_data"] += 1

    events.sort(key=lambda e: e.utc_time)
    report = _build_report(events, counters, type_counts, devices, serials, unknown_cols,
                           units, fmt, how, tz_name, meta, unparsed, len(rows))
    return ParseResult(events=events, report=report, file_hash=file_hash)


# --------------------------------------------------------------------------
# Report (also the way to identify the sensor family)
# --------------------------------------------------------------------------


def _sensor_hint(devices: Counter, median_interval) -> str:
    names = " | ".join(d for d in devices if d).lower()
    if "libre 3" in names:
        base = "Libre 3 family (device name)"
    elif "libre 2 plus" in names:
        base = "Libre 2 Plus (device name)"
    elif "librelink" in names or "libre 2" in names:
        base = "LibreLink app / Libre 1-2 family (device name)"
    else:
        base = "unknown (device name not recognised)"
    return f"{base}; automatic-reading median interval: {median_interval:g} min" if median_interval else base


def _build_report(events, counters, type_counts, devices, serials, unknown_cols, units,
                  fmt, how, tz_name, meta, unparsed, n_rows) -> dict:
    auto = sorted(e.utc_time for e in events if e.kind == "glucose_auto")
    intervals = [(b - a).total_seconds() / 60 for a, b in zip(auto, auto[1:])]
    gaps = [x for x in intervals if x > 30]
    median_iv = round(statistics.median(intervals), 1) if intervals else None
    all_local = [e.local_time for e in events]
    return {
        "rows_in_file": n_rows,
        "events_created": len(events),
        "events_by_kind": dict(Counter(e.kind for e in events)),
        "record_type_counts": dict(type_counts),
        "date_range_local": [min(all_local).isoformat(sep=" "), max(all_local).isoformat(sep=" ")] if all_local else None,
        "devices": dict(devices),
        "serial_numbers_seen": len([s for s in serials if s]),
        "glucose_units_in_file": units,
        "date_format_used": fmt,
        "date_format_resolution": how,
        "timezone_assumed": tz_name,
        "auto_reading_interval_minutes": {
            "count": len(auto), "median": median_iv,
            "most_common_rounded": Counter(round(x) for x in intervals).most_common(5),
        },
        "gaps_over_30_min": {
            "count": len(gaps), "total_hours": round(sum(gaps) / 60, 1) if gaps else 0,
            "longest_min": round(max(gaps)) if gaps else 0,
        },
        "duplicate_rows_dropped": counters["duplicate_rows_dropped"],
        "empty_rows_discarded": counters["empty_rows_discarded"],
        "rows_wrong_length": counters["rows_wrong_length"],
        "rows_bad_timestamp": counters["rows_bad_timestamp"],
        "rows_with_unmapped_data": counters["rows_with_unmapped_data"],
        "dst_flagged_rows": counters["dst_flagged_rows"],
        "unknown_columns": unknown_cols,
        "provider_export": meta["provider_export"],
        "privacy": {
            "account_name_discarded": meta["account_name_discarded"],
            "extra_metadata_rows_discarded": meta["extra_rows_discarded"],
            "note": "The export contains the account holder's name; it was not read or stored.",
        },
        "likely_sensor_family": _sensor_hint(devices, median_iv),
        "unparsed_row_examples": unparsed[:5],
    }


# --------------------------------------------------------------------------
# Optional idempotent SQLite store (demonstrates spec rule 7)
# --------------------------------------------------------------------------

_SCHEMA = """
CREATE TABLE IF NOT EXISTS import_batch (
  id INTEGER PRIMARY KEY, file_hash TEXT NOT NULL, imported_at TEXT NOT NULL, report_json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS event (
  id INTEGER PRIMARY KEY, batch_id INTEGER NOT NULL REFERENCES import_batch(id),
  row_hash TEXT NOT NULL, kind TEXT NOT NULL, utc_time TEXT NOT NULL, local_time TEXT NOT NULL,
  source_row INTEGER NOT NULL, serial TEXT, device TEXT, flags TEXT, data_json TEXT NOT NULL,
  UNIQUE(row_hash, kind, data_json));
"""


def import_into_db(conn: sqlite3.Connection, result: ParseResult) -> dict:
    """Insert events; rows already present (same content) are skipped, never duplicated."""
    conn.executescript(_SCHEMA)
    cur = conn.execute(
        "INSERT INTO import_batch(file_hash, imported_at, report_json) VALUES (?,?,?)",
        (result.file_hash, datetime.now(timezone.utc).isoformat(), json.dumps(result.report)))
    batch_id = cur.lastrowid
    new = skipped = 0
    for e in result.events:
        c = conn.execute(
            "INSERT OR IGNORE INTO event(batch_id,row_hash,kind,utc_time,local_time,source_row,serial,device,flags,data_json)"
            " VALUES (?,?,?,?,?,?,?,?,?,?)",
            (batch_id, e.row_hash, e.kind, e.utc_time.isoformat(), e.local_time.isoformat(),
             e.source_row, e.serial, e.device, json.dumps(e.flags), json.dumps(e.data, sort_keys=True)))
        if c.rowcount:
            new += 1
        else:
            skipped += 1
    conn.commit()
    return {"batch_id": batch_id, "new_events": new, "skipped_existing": skipped}


# --------------------------------------------------------------------------
# Command line
# --------------------------------------------------------------------------


def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(description="Parse a LibreView CSV and print an import report.")
    ap.add_argument("file")
    ap.add_argument("--tz", default="Europe/London", help="Time zone of the device clock")
    ap.add_argument("--date-format", default=None, help="strptime format, if the file is ambiguous")
    args = ap.parse_args(argv)
    res = parse_libreview(args.file, tz_name=args.tz, date_format=args.date_format)
    print(json.dumps(res.report, indent=2, default=str))


if __name__ == "__main__":
    main()
