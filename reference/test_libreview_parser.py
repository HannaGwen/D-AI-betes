class IdempotencyTests(unittest.TestCase):
    def _rows(self, a, b):
        return [row(us_ts(14, 8 + (m // 60), m % 60), 0, hist=str(100 + m)) for m in range(a, b, 15)]

    def test_reimport_and_overlap_create_no_duplicates(self):
        conn = sqlite3.connect(":memory:")
        file1 = build(self._rows(0, 180))          # 0..165
        file2 = build(self._rows(90, 270))         # overlaps 90..165
        r1 = import_into_db(conn, parse_libreview(file1, tz_name="America/New_York"))
        r1b = import_into_db(conn, parse_libreview(file1, tz_name="America/New_York"))
        r2 = import_into_db(conn, parse_libreview(file2, tz_name="America/New_York"))
        self.assertEqual(r1["new_events"], 12)
        self.assertEqual(r1b["new_events"], 0)
        self.assertEqual(r1b["skipped_existing"], 12)
        self.assertEqual(r2["new_events"], 6)       # only 180..255 are new
        total = conn.execute("SELECT COUNT(*) FROM event").fetchone()[0]
        self.assertEqual(total, 18)


