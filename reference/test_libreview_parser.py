"""
Tests for libreview_parser.py using SYNTHETIC fixtures only.

The fixtures copy the structure observed in a public sample export and in forum
posts (see Phase 0a spec, section 5.1). Insulin (type 4) rows are an ASSUMPTION:
the public sample contained none, so that layout must be re-checked against a real
export before it is trusted.

Optional: set LIBREVIEW_SAMPLE=/path/to/public_sample.csv to also run the checks in
PublicSampleTest. Do not commit real personal exports.

Run:  python3 -m unittest -v test_libreview_parser
"""

import io
import json
import os
import sqlite3
import unittest

from libreview_parser import (AmbiguousDateFormat, ParseError, import_into_db,
                              parse_libreview)

FAKE_NAME = "Test Persona"      # must never appear in any output

HEADER_MG = ("Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mg/dL,"
             "Scan Glucose mg/dL,Non-numeric Rapid-Acting Insulin,Rapid-Acting Insulin (units),"
             "Non-numeric Food,Carbohydrates (grams),Carbohydrates (servings),"
             "Non-numeric Long-Acting Insulin,Long-Acting Insulin (units),Notes,"
             "Strip Glucose mg/dL,Ketone mmol/L,Meal Insulin (units),Correction Insulin (units),"
             "User Change Insulin (units)")
HEADER_MMOL = HEADER_MG.replace("mg/dL", "mmol/L")
N_COLS = 19


def row(ts, rtype, device="FreeStyle LibreLink", serial="SER-1", hist="", scan="",
        rapid_marker="", rapid="", food_marker="", carbs="", servings="", long_marker="",
        long_u="", notes="", strip="", ketone="", meal="", corr="", user=""):
    return [device, serial, ts, str(rtype), hist, scan, rapid_marker, rapid, food_marker, carbs,
            servings, long_marker, long_u, notes, strip, ketone, meal, corr, user]


def build(rows, header=HEADER_MG, delim=",", meta="us", gen="07-20-2021 02:05 PM UTC"):
    """Return bytes of a LibreView-like export."""
    import csv as _csv
    hdr = header.split(",")
    buf = io.StringIO()
    w = _csv.writer(buf, delimiter=delim, lineterminator="\n")   # quotes cells that need it
    if meta == "us":
        w.writerow(["Glucose Data", "Generated on", gen, "Generated by", FAKE_NAME])
    elif meta == "provider":
        w.writerow(["Patient report", "Generated on", gen, "Generated by", "Dr Clinician"])
        w.writerow([FAKE_NAME, "1/1/1980"])
    w.writerow(hdr)
    for r in rows:
        w.writerow(r)
    return buf.getvalue().encode("utf-8")


def us_ts(day, hh, mm):          # 07-DD-2021 hh:mm AM/PM
    ap = "AM" if hh < 12 else "PM"
    h12 = hh % 12 or 12
    return f"07-{day:02d}-2021 {h12:02d}:{mm:02d} {ap}"


class CoreTests(unittest.TestCase):
    def test_us_12h_basic_and_privacy(self):
        data = build([row(us_ts(14, 8, 0), 0, hist="100"), row(us_ts(14, 8, 15), 0, hist="105"),
                      row(us_ts(14, 8, 20), 1, scan="110")])
        res = parse_libreview(data, tz_name="America/New_York")
        self.assertEqual(res.report["events_by_kind"], {"glucose_auto": 2, "glucose_scan": 1})
        self.assertEqual(res.report["date_format_resolution"], "unambiguous")
        blob = json.dumps(res.report, default=str) + json.dumps([e.data for e in res.events])
        self.assertNotIn(FAKE_NAME, blob)
        self.assertTrue(res.report["privacy"]["account_name_discarded"])

    def test_provider_export_discards_name_and_dob_row(self):
        data = build([row("7/14/2021 8:00", 0, hist="100"), row("7/14/2021 8:15", 0, hist="101")],
                     meta="provider", gen="07-20-2021 02:05 PM UTC")
        res = parse_libreview(data, tz_name="America/New_York")
        self.assertTrue(res.report["provider_export"])
        self.assertEqual(res.report["privacy"]["extra_metadata_rows_discarded"], 1)
        blob = json.dumps(res.report, default=str) + json.dumps([e.data for e in res.events])
        self.assertNotIn(FAKE_NAME, blob)
        self.assertNotIn("1980", blob)

    def test_mmol_conversion_and_uk_24h(self):
        rows = [row("14-09-2022 08:00", 0, hist="5.5"), row("14-09-2022 08:15", 0, hist="10.0")]
        data = build(rows, header=HEADER_MMOL, gen="17-09-2022 15:40 UTC")
        res = parse_libreview(data)
        vals = [e.data["value_mgdl"] for e in res.events]
        self.assertAlmostEqual(vals[0], 99.1, places=1)
        self.assertAlmostEqual(vals[1], 180.2, places=1)
        self.assertEqual(res.events[0].data["orig_unit"], "mmol/L")
        self.assertEqual(res.report["glucose_units_in_file"]["hist_glucose"], "mmol/L")

    def test_semicolon_with_decimal_comma(self):
        rows = [row("14-09-2022 08:00", 0, hist="5,5")]   # decimal comma, semicolon delimiter
        data = build(rows, header=HEADER_MMOL, delim=";", gen="17-09-2022 15:40 UTC")
        res = parse_libreview(data)
        self.assertAlmostEqual(res.events[0].data["value_mgdl"], 99.1, places=1)

    def test_tab_delimited(self):
        rows = [row("14-09-2022 08:00", 0, hist="5.5")]
        data = build(rows, header=HEADER_MMOL, delim="\t", gen="17-09-2022 15:40 UTC")
        res = parse_libreview(data)
        self.assertEqual(res.report["events_by_kind"], {"glucose_auto": 1})

    def test_empty_type6_discarded_and_type5_without_carbs(self):
        rows = [row(us_ts(14, 8, 0), 0, hist="100"),
                row(us_ts(14, 8, 1), 6), row(us_ts(14, 8, 1), 6),         # empty, repeated
                row(us_ts(14, 12, 30), 5, food_marker="1"),                  # marker, no carbs
                row(us_ts(14, 12, 31), 6, notes="lunch note")]
        res = parse_libreview(build(rows), tz_name="America/New_York")
        self.assertEqual(res.report["empty_rows_discarded"], 2)
        food = [e for e in res.events if e.kind == "food"][0]
        self.assertIsNone(food.data["carbs_g"])
        self.assertTrue(food.data["marker_only"])
        self.assertEqual([e.data["text"] for e in res.events if e.kind == "note"], ["lunch note"])

    def test_insulin_rows_assumed_layout(self):
        rows = [row(us_ts(14, 12, 30), 4, rapid="6"), row(us_ts(14, 22, 0), 4, long_u="14")]
        res = parse_libreview(build(rows), tz_name="America/New_York")
        ins = [e.data for e in res.events if e.kind == "insulin"]
        self.assertEqual({(i["role"], i["units"]) for i in ins}, {("rapid", 6.0), ("long", 14.0)})
        self.assertTrue(all(i["confidence"] == "low" for i in ins))

    def test_note_with_comma_is_quoted_and_kept(self):
        res = parse_libreview(build([row(us_ts(14, 8, 0), 6, notes="lunch, light")]), tz_name="America/New_York")
        self.assertEqual([e.data["text"] for e in res.events if e.kind == "note"], ["lunch, light"])

    def test_hi_lo_text_is_kept_not_crashing(self):
        res = parse_libreview(build([row(us_ts(14, 8, 0), 0, hist="HI")]), tz_name="America/New_York")
        e = res.events[0]
        self.assertIsNone(e.data["value_mgdl"])
        self.assertIn("non_numeric_glucose", e.flags)

    def test_in_file_duplicates_dropped(self):
        r = row(us_ts(14, 8, 0), 0, hist="100")
        res = parse_libreview(build([r, r]), tz_name="America/New_York")
        self.assertEqual(res.report["duplicate_rows_dropped"], 1)
        self.assertEqual(len(res.events), 1)

    def test_irregular_intervals_and_gaps_from_real_timestamps(self):
        mins = [0, 15, 31, 46, 62, 62 + 123]      # 16, 15, 16, 123-minute gap
        rows = [row(us_ts(14, 8 + (m // 60), m % 60), 0, hist=str(100 + i)) for i, m in enumerate(mins)]
        res = parse_libreview(build(rows), tz_name="America/New_York")
        gaps = res.report["gaps_over_30_min"]
        self.assertEqual(gaps["count"], 1)
        self.assertEqual(gaps["longest_min"], 123)

    def test_wrong_length_row_is_reported_not_fatal(self):
        data = build([row(us_ts(14, 8, 0), 0, hist="100")]) + b"short,row\n"
        res = parse_libreview(data, tz_name="America/New_York")
        self.assertEqual(res.report["rows_wrong_length"], 1)
        self.assertEqual(len(res.events), 1)

    def test_unknown_extra_column_reported(self):
        hdr = HEADER_MG + ",Mystery Column"
        rows = [row(us_ts(14, 8, 0), 0, hist="100") + ["x"]]
        res = parse_libreview(build(rows, header=hdr), tz_name="America/New_York")
        self.assertEqual(res.report["unknown_columns"], ["Mystery Column"])

    def test_sensor_family_hint(self):
        res = parse_libreview(build([row("07-14-2021 08:00 AM", 0, device="FreeStyle Libre 3", hist="100")]),
                              tz_name="America/New_York")
        self.assertIn("Libre 3", res.report["likely_sensor_family"])


class DateTests(unittest.TestCase):
    def test_ambiguous_resolved_by_generated_on(self):
        # All days <= 12. Read as day-first this is 3-5 Apr 2023, exported 6 Apr.
        rows = [row("03-04-2023 08:00", 0, hist="100"), row("04-04-2023 08:00", 0, hist="101"),
                row("05-04-2023 08:00", 0, hist="102")]
        res = parse_libreview(build(rows, gen="06-04-2023 10:00 AM UTC"))
        self.assertEqual(res.report["date_format_resolution"], "resolved_by_generated_on")
        self.assertEqual(res.events[-1].local_time.month, 4)

    def test_truly_ambiguous_raises(self):
        rows = [row("03-04-2023 08:00", 0, hist="100"), row("04-04-2023 08:00", 0, hist="101")]
        with self.assertRaises(AmbiguousDateFormat):
            parse_libreview(build(rows, gen="20-09-2023 10:00 AM UTC"))

    def test_forced_format_overrides(self):
        rows = [row("03-04-2023 08:00", 0, hist="100")]
        res = parse_libreview(build(rows, gen="20-09-2023 10:00 AM UTC"), date_format="%d-%m-%Y %H:%M")
        self.assertEqual(res.events[0].local_time.month, 4)
        self.assertEqual(res.report["date_format_resolution"], "user_supplied")

    def test_dst_flags_london(self):
        rows = [row("26-03-2023 01:30", 0, hist="100"),    # skipped hour (spring forward)
                row("29-10-2023 01:30", 0, hist="101"),    # repeated hour (fall back)
                row("15-06-2023 12:00", 0, hist="102")]    # ordinary
        res = parse_libreview(build(rows, gen="30-10-2023 09:00 UTC"), tz_name="Europe/London")
        flags = {e.local_time.strftime("%d-%m"): e.flags for e in res.events}
        self.assertEqual(flags["26-03"], ["dst_nonexistent"])      # only that flag
        self.assertEqual(flags["29-10"], ["dst_ambiguous"])
        self.assertEqual(flags["15-06"], [])
        self.assertEqual(res.report["dst_flagged_rows"], 2)

    def test_utc_conversion_summer(self):
        res = parse_libreview(build([row("15-06-2023 12:00", 0, hist="100")], gen="16-06-2023 09:00 UTC"),
                              tz_name="Europe/London")
        self.assertEqual(res.events[0].utc_time.hour, 11)


