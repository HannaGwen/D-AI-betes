// Guards for privacy/offline properties that are easy to break by accident.
import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildCsvs, toCsv } from "../src/exportcsv.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = path.join(root, "src");
const srcFiles = fs.readdirSync(srcDir).filter((f) => f.endsWith(".js"));
const read = (p) => fs.readFileSync(p, "utf8");

test("app code has no external URLs, eval, innerHTML, document.write or localStorage", () => {
  for (const f of srcFiles) {
    const code = read(path.join(srcDir, f));
    assert.ok(!/https?:\/\//.test(code), `${f}: contains a URL`);
    assert.ok(!/\beval\s*\(|new Function\s*\(/.test(code), `${f}: eval/Function`);
    assert.ok(!/innerHTML|outerHTML|insertAdjacentHTML|document\.write/.test(code), `${f}: HTML injection API`);
    assert.ok(!/localStorage|sessionStorage|XMLHttpRequest|WebSocket|sendBeacon|EventSource/.test(code), `${f}: unexpected storage/network API`);
  }
});

test("only the service worker and nothing else uses fetch()", () => {
  for (const f of srcFiles) assert.ok(!/\bfetch\s*\(/.test(read(path.join(srcDir, f))), `${f}: fetch`);
  assert.ok(/fetch\(e\.request\)/.test(read(path.join(root, "sw.js"))));       // same-origin app files only
});

test("index.html has a strict content security policy and no inline script/style", () => {
  const html = read(path.join(root, "index.html"));
  const csp = /Content-Security-Policy" content="([^"]+)"/.exec(html)[1];
  assert.ok(csp.includes("default-src 'none'"));
  assert.ok(csp.includes("script-src 'self'") && !csp.includes("unsafe-inline") && !csp.includes("unsafe-eval"));
  assert.ok(!/connect-src[^;]*https?:/.test(csp));                              // no external connections
  assert.ok(!/<script(?![^>]*src=)[^>]*>/.test(html), "inline script");
  assert.ok(!/ style="/.test(html), "inline style attribute");
  assert.ok(!/(href|src)="https?:/.test(html), "external resource");
});

test("no inline style attributes are generated by the app", () => {
  for (const f of srcFiles) assert.ok(!/setAttribute\(["']style["']|style:\s*["']/.test(read(path.join(srcDir, f))), f);
});

test("service worker precaches every source file and the icons", () => {
  const sw = read(path.join(root, "sw.js"));
  for (const f of srcFiles) assert.ok(sw.includes(`"src/${f}"`), `sw.js is missing src/${f}`);
  for (const f of ["index.html", "styles.css", "manifest.webmanifest"]) assert.ok(sw.includes(`"${f}"`), f);
  for (const m of sw.matchAll(/"(assets\/[^"]+)"/g)) assert.ok(fs.existsSync(path.join(root, m[1])), m[1]);
});

test("manifest uses relative paths (works under a GitHub Pages sub-path)", () => {
  const m = JSON.parse(read(path.join(root, "manifest.webmanifest")));
  assert.equal(m.start_url, "./"); assert.equal(m.scope, "./"); assert.equal(m.display, "standalone");
  for (const i of m.icons) { assert.ok(!i.src.startsWith("/")); assert.ok(fs.existsSync(path.join(root, i.src))); }
});

test("no real or personal data is committed in fixtures", () => {
  for (const f of fs.readdirSync(path.join(root, "tests", "fixtures"))) {
    const t = read(path.join(root, "tests", "fixtures", f));
    assert.ok(!/Martha|Sprague/.test(t), f);
  }
});

test("CSV export quotes commas, quotes and newlines", () => {
  assert.equal(toCsv(["a", "b"], [{ a: 'x,"y"', b: "line\nbreak" }]), 'a,b\n"x,""y""","line\nbreak"\n');
  const exp = { glucose: [{ t: Date.UTC(2023, 5, 15, 11, 0), mgdl: 99.1, kind: "auto", b: "batch:1" }],
    doses: [{ id: "d1", t: Date.UTC(2023, 5, 15, 11, 5), role: "rapid", units: 6, purpose: "meal", source: "app", confidence: "high" }],
    meals: [{ id: "m1", t: Date.UTC(2023, 5, 15, 11, 10), title: "Lunch, light", totals: { carb: 40 }, items: [{ name: "x" }], carbsUsedForDosing: 45 }],
    tags: [{ id: "t1", t: Date.UTC(2023, 5, 15, 11, 15), tag: "exercise", durationMin: 30, payload: { type: "aerobic" } }] };
  const csv = buildCsvs(exp, "Europe/London");
  assert.deepEqual(Object.keys(csv), ["glucose.csv", "doses.csv", "meals.csv", "tags.csv"]);
  assert.match(csv["glucose.csv"], /2023-06-15T11:00:00\+00:00,2023-06-15 12:00,99.1,5.5,auto,batch:1,/);
  assert.match(csv["meals.csv"], /"Lunch, light",40,,,,,45/);
  assert.match(csv["tags.csv"], /exercise,30,"{""type"":""aerobic""}"/);
});

test(".gitignore blocks the app's export and backup files", () => {
  const gi = read(path.join(root, ".gitignore"));
  for (const pat of ["node_modules/", "t1dlog-export-*", "t1dlog-backup-*", "t1dlog-*-glucose.csv", "t1dlog-*-doses.csv"]) assert.ok(gi.includes(pat), pat);
});
